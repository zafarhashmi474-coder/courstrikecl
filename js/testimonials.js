/* =========================================================
   GET ID FROM URL
   ========================================================= */

function getCurrentId() {

    const params = new URLSearchParams(window.location.search);

    return Number(params.get("id"));
}


/* =========================================================
   GET TESTIMONIAL BY ID
   ========================================================= */

function getTestimonialById(id) {

    return testimonials.find(item => item.id === id);

}


/* =========================================================
   CREATE CARD
   ========================================================= */

function createTestimonialCard(testimonial) {

    let link;

    /*
       ID 1 - 7
       → testimonial-detail.html

       ID 8 - 37
       → learner-profile.html
    */

    if (testimonial.id >= 8) {

        link = `learner-profile.html?id=${testimonial.id}`;

    } else {

        link = `testimonial-detail.html?id=${testimonial.id}`;

    }


    return `
        <a href="${link}" class="testimonial-card">

            <div class="testimonial-image-wrapper">

                <img
                    src="${testimonial.image}"
                    alt="${testimonial.name}"
                    class="testimonial-image"
                >

            </div>


            <div class="testimonial-info">

                <div>

                    <h3 class="testimonial-name">
                        ${testimonial.name}
                    </h3>

                    <p class="testimonial-role">
                        ${testimonial.role}
                    </p>

                </div>


                <span class="testimonial-arrow">
                    →
                </span>

            </div>

        </a>
    `;
}


/* =========================================================
   RENDER TESTIMONIAL LIST
   ========================================================= */

function renderTestimonials() {

    const firstGrid =
        document.getElementById("firstTestimonialsGrid");

    const remainingGrid =
        document.getElementById("remainingTestimonialsGrid");


    if (!firstGrid && !remainingGrid) {
        return;
    }


    /*
       FIRST 3
    */

    if (firstGrid) {

        firstGrid.innerHTML = testimonials
            .slice(0, 3)
            .map(createTestimonialCard)
            .join("");

    }


    /*
       REMAINING
    */

    if (remainingGrid) {

        remainingGrid.innerHTML = testimonials
            .slice(3)
            .map(createTestimonialCard)
            .join("");

    }

}


/* =========================================================
   LOAD OLD TESTIMONIAL DETAIL PAGE
   ID 1 - 7
   ========================================================= */

function loadTestimonialDetail() {

    const nameElement =
        document.getElementById("detailName");

    /*
       If detailName doesn't exist,
       this is not testimonial-detail.html.
    */

    if (!nameElement) {
        return;
    }


    const id = getCurrentId();

    const testimonial =
        getTestimonialById(id);


    if (!testimonial) {

        console.error("Testimonial not found:", id);

        return;

    }


    /*
       NAME
    */

    nameElement.textContent =
        testimonial.name;


    /*
       GRADUATION
    */

    const graduation =
        document.getElementById("detailGraduation");

    if (graduation) {

        graduation.textContent =
            testimonial.graduation || "";

    }


    /*
       ROLE
    */

    const role =
        document.getElementById("detailRole");

    if (role) {

        role.textContent =
            testimonial.role || "";

    }


    /*
       LOGO
    */

    const logo =
        document.getElementById("detailLogo");

    if (logo) {

        if (testimonial.logo) {

            logo.src =
                testimonial.logo;

            logo.alt =
                testimonial.role || "Company logo";

            logo.style.display =
                "block";

        } else {

            logo.style.display =
                "none";

        }

    }


    /*
       IMAGE
    */

    const image =
        document.getElementById("detailImage");

    if (image) {

        image.src =
            testimonial.image;

        image.alt =
            testimonial.name;

    }


    /*
       QUOTE
    */

    const quote =
        document.getElementById("detailQuote");

    if (quote) {

        quote.textContent =
            testimonial.quote || "";

    }


    /*
       DESCRIPTION
    */

    const description =
        document.getElementById("detailDescription");

    if (description) {

        description.textContent =
            testimonial.description || "";

    }

}


/* =========================================================
   LOAD LEARNER PROFILE
   ID 8 - 37
   ========================================================= */

function loadLearnerProfile() {

    const learnerName =
        document.getElementById("learnerName");


    /*
       If learnerName doesn't exist,
       this is not learner-profile.html.
    */

    if (!learnerName) {
        return;
    }


    const id = getCurrentId();

    const learner =
        getTestimonialById(id);


    if (!learner) {

        console.error("Learner not found:", id);

        return;

    }


    /*
       NAME
    */

    learnerName.textContent =
        learner.name;


    /*
       ROLE
    */

    const learnerRole =
        document.getElementById("learnerRole");

    if (learnerRole) {

        learnerRole.textContent =
            learner.role || "";

    }


    /*
       COURSE
    */

    const learnerCourse =
        document.getElementById("learnerCourse");

    if (learnerCourse) {

        learnerCourse.textContent =
            learner.course ||
            "Digital Skills Certification";

    }


    /*
       SKILLS
    */

    const learnerSkills =
        document.getElementById("learnerSkills");

    if (learnerSkills) {

        const skills =
            learner.skills || [];


        if (skills.length > 0) {

            learnerSkills.innerHTML =
                skills.map(skill => {

                    return `
                        <li>
                            <span class="skill-check">✓</span>
                            <span>${skill}</span>
                        </li>
                    `;

                }).join("");

        } else {

            learnerSkills.innerHTML = `
                <li>
                    <span class="skill-check">✓</span>
                    <span>Digital Skills</span>
                </li>

                <li>
                    <span class="skill-check">✓</span>
                    <span>Technology</span>
                </li>

                <li>
                    <span class="skill-check">✓</span>
                    <span>Professional Development</span>
                </li>
            `;

        }

    }


    /*
       IMAGE
    */

    const learnerImage =
        document.getElementById("learnerImage");

    if (learnerImage) {

        learnerImage.src =
            learner.image;

        learnerImage.alt =
            learner.name;

    }


    /*
       QUESTIONS + ANSWERS
    */

    const questionsContainer =
        document.getElementById("learnerQuestions");


    if (questionsContainer) {

        const questions =
            learner.questions || [];


        if (questions.length > 0) {

            questionsContainer.innerHTML =
                questions.map(item => {

                    return `
                        <div class="question-item">

                            <h2 class="question">
                                ${item.question}
                            </h2>

                            <p class="answer">
                                ${item.answer}
                            </p>

                        </div>
                    `;

                }).join("");

        } else {

            /*
               For learners whose real Q&A
               hasn't been added yet.
            */

            questionsContainer.innerHTML = `
                <div class="question-item">

                    <h2 class="question">
                        About ${learner.name}'s learning experience
                    </h2>

                    <p class="answer">
                        ${learner.description || ""}
                    </p>

                </div>
            `;

        }

    }

}


/* =========================================================
   RELATED STORIES
   ========================================================= */

function renderRelatedTestimonials() {

    const relatedContainer =
        document.getElementById("relatedTestimonials");


    if (!relatedContainer) {
        return;
    }


    const currentId =
        getCurrentId();


    /*
       Remove current learner from
       related stories.
    */

    const related =
        testimonials
            .filter(item => item.id !== currentId)
            .slice(0, 3);


    relatedContainer.innerHTML =
        related.map(testimonial => {

            let link;

            if (testimonial.id >= 8) {

                link =
                    `learner-profile.html?id=${testimonial.id}`;

            } else {

                link =
                    `testimonial-detail.html?id=${testimonial.id}`;

            }


            return `
                <a
                    href="${link}"
                    class="related-card"
                >

                    <div class="related-image-wrapper">

                        <img
                            src="${testimonial.image}"
                            alt="${testimonial.name}"
                            class="related-image"
                        >

                    </div>


                    <div class="related-info">

                        <div>

                            <h3 class="related-name">
                                ${testimonial.name}
                            </h3>

                            <p class="related-role">
                                ${testimonial.role}
                            </p>

                        </div>


                        <span class="related-arrow">
                            →
                        </span>

                    </div>

                </a>
            `;

        }).join("");

}


